// Writes docs/SETTINGS.md from the menu's own catalog, so the page cannot drift from the code.
//
//   g++ -std=c++20 -Ifrontend tools/settings-doc.cpp frontend/menu/settings_model.cpp -o settings-doc
//   ./settings-doc > docs/SETTINGS.md
//
// tests/docs_check.sh rebuilds this and fails when docs/SETTINGS.md is not what the code says.

#include <cstdio>
#include <string>

#include "menu/settings_model.h"

namespace {

const char* GroupTitle(Menu::Group group) {
    switch (group) {
    case Menu::Group::Video:
        return "VIDEO tab (video, GPU and speed)";
    case Menu::Group::Cpu:
        return "CPU AND MEMORY tab";
    case Menu::Group::Advanced:
        return "ADVANCED options";
    case Menu::Group::System:
        return "SYSTEM tab";
    case Menu::Group::Perf:
        return "HUD tab (the HUD, notices and covers)";
    case Menu::Group::Controls:
        return "CONTROLS tab";
    }
    return "";
}

/// Table cells cannot hold a pipe or a line break.
std::string Cell(const std::string& text) {
    std::string out;
    for (const char c : text) {
        if (c == '|') {
            out += "\\|";
        } else if (c == '\n') {
            out += ' ';
        } else {
            out += c;
        }
    }
    return out;
}

} // namespace

int main() {
    std::printf("<!-- Generated by tools/settings-doc.cpp from frontend/menu/settings_model.cpp. Do not edit by hand. -->\n");
    std::printf("# Options and quick profiles\n\n");
    std::printf("Every option of the in-app menu, as `settings.txt` keys (`/data/edenps4/settings.txt`, one `key=value` per line,\n"
                "`#` starts a comment). The menu writes the file for you; an option set back to its default has its line removed,\n"
                "so \"default\" always means whatever this version defaults to. A key written by hand that the menu does not\n"
                "know is kept as it is. `env:NAME` is the line `env=NAME=value` (a driver environment variable).\n\n");
    std::printf("The value marked **(default)** is what you get with no line in the file. Texts are the menu's English ones;\n"
                "the menu also has them in Portuguese.\n\n"
                "Since 0.9.5 the last column says who sees an option: **yes** (always), **TESTS tab** (only the test builds, which\n"
                "have the EXPERIMENTAL/TESTS tab and the LOG tab; a release for everyone, built with `EDEN_PS4_PUBLIC=1`, has\n"
                "neither) or **hidden** (the default is what this port needs, so the menu does not offer a switch). A line for\n"
                "any of them written by hand in `settings.txt` still works, and `show_advanced=on` shows all of them in the\n"
                "TESTS tab.\n\n"
                "**Per game** (0.9.5). R2 on a game in the game list opens that game's own options. They are saved in\n"
                "`/data/edenps4/per-game/<title id>.txt` (the title id in the game's file name, like `[0100000000010000]`; without one, the\n"
                "file name without its extension, letters, digits and `-` kept, the rest turned into `_`), with the same `key=value` lines as\n"
                "`settings.txt`, and applied **on top of it** when that game starts: an option the game's file does not name keeps the\n"
                "global value. The last column says which options a game's file may set. The ones that are global (`language`, `menu_theme`,\n"
                "`covers`, `memory_profile`, `show_advanced`) are skipped with a line in `boot.log`. In the R2 screen each option reads\n"
                "`global (value)` until you pick one for the game; Triangle puts one back to global.\n\n");

    const auto& catalog = Menu::Catalog();
    int count = 0;
    for (int g = 0; g <= int(Menu::Group::Controls); ++g) {
        // The order of the groups in the menu's tabs.
        static const Menu::Group order[] = {Menu::Group::Controls, Menu::Group::Video, Menu::Group::Cpu, Menu::Group::Perf,
                                            Menu::Group::System, Menu::Group::Advanced};
        const Menu::Group group = order[g];
        bool header = false;
        for (const auto& option : catalog) {
            if (option.group != group) {
                continue;
            }
            if (!header) {
                std::printf("## %s\n\n| Key | Option | Values | What it does | In the menu | Per game |\n|---|---|---|---|---|---|\n", GroupTitle(group));
                header = true;
            }
            std::string values;
            for (size_t i = 0; i < option.choices.size(); ++i) {
                if (i != 0) {
                    values += ", ";
                }
                values += std::string("`") + option.choices[i].value + "`";
                if (int(i) == option.default_index) {
                    values += " **(default)**";
                }
            }
            const Menu::Tier tier = Menu::TierOf(option.key);
            const char* shown = tier == Menu::Tier::Mandatory      ? "hidden (the default is what this port needs)"
                                : tier == Menu::Tier::Experimental ? "TESTS tab, test builds only"
                                                                   : "yes";
            const char* per_game = Menu::GlobalOnly(option.key)          ? "no (global only)"
                                   : Menu::PerGameOffered(option)        ? "yes (R2)"
                                   : tier == Menu::Tier::Mandatory       ? "by hand only"
                                                                         : "by hand only (not offered)";
            std::printf("| `%s` | %s | %s | %s | %s | %s |\n", option.key, Cell(option.label_en).c_str(), Cell(values).c_str(),
                        Cell(option.help_en).c_str(), shown, per_game);
            ++count;
        }
        if (header) {
            std::printf("\n");
        }
    }

    std::printf("## Quick profiles\n\nThe first row of the VIDEO tab sets several options at once, to try combinations fast. They do not promise\n"
                "that a game will open. Options a profile does not name go back to their defaults.\n\n"
                "| Profile | Sets | What it is for |\n|---|---|---|\n");
    for (const auto& preset : Menu::Presets()) {
        std::string sets;
        for (const auto& value : preset.values) {
            if (!sets.empty()) {
                sets += ", ";
            }
            sets += std::string("`") + value.first + "=" + value.second + "`";
        }
        if (sets.empty()) {
            sets = "(nothing: every option at its default)";
        }
        std::printf("| %s | %s | %s |\n", Cell(preset.en).c_str(), Cell(sets).c_str(), Cell(preset.help_en).c_str());
    }
    std::printf("\n%d options, %zu profiles.\n", count, Menu::Presets().size());
    return 0;
}
